function growthSeries(daysCount: number, base: number) {
  return Array.from({ length: daysCount }, (_, i) => {
    const date = new Date(now - (daysCount - 1 - i) * 86400000);
    return {
      date: date.toISOString().slice(0, 10),
      count: base + i * 2 + (i % 3),
    };
  });
}

function volumeSeries(daysCount: number) {
  return Array.from({ length: daysCount }, (_, i) => {
    const date = new Date(now - (daysCount - 1 - i) * 86400000);
    return {
      date: date.toISOString().slice(0, 10),
      count: 40 + Math.round(Math.sin(i / 2) * 15) + (i % 5) * 3,
    };
  });
}

export function getMockAdminStats(): AdminStats {
  const active = mockMailboxes.filter((m) => m.status === "active").length;
  const suspended = mockMailboxes.filter((m) => m.status === "suspended").length;
  const createdToday = mockMailboxes.filter(
    (m) => new Date(m.createdAt).toDateString() === new Date().toDateString()
  ).length;
  const storageUsed = mockMailboxes.reduce((sum, m) => sum + m.storageUsed, 0);

  return {
    totalMailboxes: mockMailboxes.length,
    activeMailboxes: active,
    suspendedMailboxes: suspended,
    mailboxesCreatedToday: createdToday,
    messagesToday: 47,
    storageUsed,
    storageLimit: 10_000_000_000,
    mailboxGrowth: growthSeries(14, 120),
    inboundVolume: volumeSeries(14),
    recentActivity: mockAuditLogs.slice(0, 6),
  };
}

