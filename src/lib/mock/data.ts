function buildMessage(
  partial: Omit<Message, "detectedCode" | "preview"> & { preview?: string }
): Message {
  const detectedCode = extractVerificationCode(
    partial.subject,
    partial.bodyText,
    partial.bodyHtml
  );
  return {
    ...partial,
    preview: partial.preview ?? partial.bodyText.slice(0, 120).replace(/\s+/g, " "),
    detectedCode,
  };
}

